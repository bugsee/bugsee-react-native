/**
 * Fails when the option manifest each native SDK published for the PINNED version disagrees with this
 * package. Run in CI and before a publish.
 *
 * It complains about what an SDK PUBLISHES that this package does not match, and about nothing else. For
 * Android and iOS it checks that
 *  - every option the SDK registers is a key this package lists (a new SDK option is named);
 *  - the committed copy of each manifest has every published option with the same type, default, hidden
 *    flag, deprecation and enum constants;
 *  - every published option has an accessor on the options classes, with a setter and a type that can
 *    hold the SDK's, and the package's enums have the SDK's constants. A missing option is reported by
 *    name;
 *  - docs/launch-options.md is what the generator renders from these, so its type and default of every
 *    option are the SDK's.
 *
 * It is deliberately one-directional. An option this package has and the SDK does not publish is fine:
 * the package can have options of its own, sent to the SDK (which ignores them) and acted on only in
 * React Native.
 *
 * Usage: cli-check-published-manifests.ts [--dir <directory>] [--update]
 *
 * By default the manifests are fetched from download.bugsee.com (override the base with
 * BUGSEE_OPTIONS_MANIFEST_BASE). `--dir` reads `<directory>/<platform>/<version>.json` instead, for
 * working offline. `--update` writes the published iOS manifest over ios-options-manifest.json (the
 * Android copy is generated by cli-extract-option-keys.ts). An unreachable manifest FAILS the check: a
 * gate that passes when it cannot look is not a gate. The fetch is retried, since the file is immutable
 * and only the network can be flaky.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  MANIFEST_BASE,
  checkAccessors,
  checkPublished,
  manifestUrl,
  parseManifest,
  type Platform,
  type PublishedManifest,
} from './published-manifest.ts';
import { readHead, renderDoc } from './launch-options-doc.ts';
import {
  accessorsFor,
  docPath,
  fixtureName,
  fixtureOptions,
  keys,
  optionsDir,
  pinned,
  readAccessors,
  readEnums,
  readNoAccessor,
} from './cli-options-sources.ts';

const dirFlag = process.argv.indexOf('--dir');
const dir = dirFlag === -1 ? undefined : process.argv[dirFlag + 1];
const update = process.argv.includes('--update');
const base = process.env.BUGSEE_OPTIONS_MANIFEST_BASE ?? MANIFEST_BASE;

async function load(platform: Platform, version: string): Promise<string> {
  if (dir !== undefined) {
    return readFileSync(join(dir, platform, `${version}.json`), 'utf8');
  }
  const url = manifestUrl(base, platform, version);
  let failure = '';
  for (let attempt = 1; attempt <= 4; attempt++) {
    try {
      const response = await fetch(url, { signal: AbortSignal.timeout(20_000) });
      if (response.ok) {
        return await response.text();
      }
      failure = `HTTP ${response.status}`;
      // A manifest that is not there will not appear by asking again (the CDN answers a missing
      // key with 403 or 404).
      if (response.status === 403 || response.status === 404) {
        break;
      }
    } catch (error) {
      failure = (error as Error).message;
    }
    await new Promise((resolve) => setTimeout(resolve, attempt * 2_000));
  }
  throw new Error(`could not fetch ${url}: ${failure}`);
}

const accessors = readAccessors();
const { enums, withheld } = await readEnums();
const noAccessor = await readNoAccessor();
const manifests: Partial<Record<Platform, PublishedManifest>> = {};
let failed = false;

function report(label: string, problems: string[]): void {
  if (problems.length === 0) {
    return;
  }
  failed = true;
  console.error(`${label}: ${problems.length} misalignment(s)`);
  for (const problem of problems) {
    console.error(`  - ${problem}`);
  }
}

for (const platform of ['android', 'ios'] as const) {
  const version = pinned[platform].sdk;
  const label = `${platform} ${version}`;
  try {
    const text = await load(platform, version);
    const published = parseManifest(text, `${label} manifest`);
    manifests[platform] = published;
    if (update && platform === 'ios') {
      writeFileSync(join(optionsDir, fixtureName('ios')), `${JSON.stringify(published, null, 2)}\n`);
      console.log(`wrote ${fixtureName('ios')}`);
    }
    const problems = [
      ...checkPublished({
        platform,
        pinnedVersion: version,
        published,
        knownKeys: [...keys.shared, ...keys[platform]],
        committed: update && platform === 'ios' ? published.options : fixtureOptions(platform),
        committedName: fixtureName(platform),
      }),
      ...checkAccessors({
        platform,
        pinnedVersion: version,
        published,
        accessors: accessorsFor(accessors, platform),
        noAccessor,
        enums,
        withheld,
      }),
    ];
    report(label, problems);
    if (problems.length === 0) {
      console.log(`${label}: aligned (${published.options.length} published options)`);
    }
  } catch (error) {
    failed = true;
    console.error(`${label}: ${(error as Error).message}`);
  }
}

if (manifests.android && manifests.ios) {
  const committed = readFileSync(docPath, 'utf8');
  const rendered = renderDoc({
    head: readHead(committed),
    android: manifests.android,
    ios: manifests.ios,
    accessors,
    noAccessor,
  });
  if (rendered !== committed) {
    failed = true;
    console.error(
      'docs/launch-options.md is out of date: its types, platforms or defaults differ from the published ' +
        'manifests and the accessors. Run `node scripts/cli-generate-launch-options-doc.ts`.',
    );
  } else {
    console.log('docs/launch-options.md: matches the published manifests');
  }
}
process.exit(failed ? 1 : 0);
