#!/usr/bin/env node
/**
 * Writes the two credential files the example app needs, from the environment,
 * and the default e2e scenario file.
 *
 * All three outputs are gitignored and none is ever committed:
 *
 *   credentials.json         read by App.tsx at runtime, for Bugsee.launch()
 *   android/bugsee.properties read by the Bugsee Gradle plugin at build time
 *
 * The Gradle plugin's token key is the unprefixed `app_token` (not
 * `plugin.appToken`), and the file belongs to the *root* Gradle project
 * (examples/bare/android), not to :app. NDK symbol upload
 * (`plugin.ndk.enabled=true`) is written only when BUGSEE_TOKEN_ANDROID is
 * non-empty and isPlaceholderToken (endpoint.ts) is false. CI's placeholder
 * token would otherwise make assembleDebug upload. Omit the key otherwise
 * so the plugin default, off, stands. That flag also makes the plugin add
 * `bugsee-android-ndk` on a version range unless :app declares the artifact
 * itself, which this app does at the pinned SDK version. A non-empty
 * BUGSEE_ENDPOINT is written as `plugin.endpoint` with no `/v2` suffix; an
 * empty one is omitted so the plugin default stands.
 *
 * Usage:
 *   BUGSEE_TOKEN_IOS=… BUGSEE_TOKEN_ANDROID=… BUGSEE_ENDPOINT=… \
 *     node scripts/write-credentials.mjs
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const appRoot = join(dirname(fileURLToPath(import.meta.url)), '..');

// Same check as isPlaceholderToken in ../endpoint.ts.
function isPlaceholderToken(token) {
  return /^0{12}[0-9a-f]0{3}[0-9a-f]0{15}$/i.test(token.replace(/-/g, ''));
}

// App.tsx imports e2e-scenario.json, so the bundle does not build without it.
// The device e2e overwrites it per run; left alone, the app runs the plain
// launch walk. Written when absent, and otherwise left alone so a scenario
// mid-run is not reset -- unless it carries an `endpoint`. Only the iOS e2e
// writes one (the closed loopback port that retains reports on the
// simulator), and an interrupted run that leaves it behind points every later
// launch of the app at a dead endpoint. Unreadable JSON is reset too: the
// bundle would not build with it.
const scenarioFile = join(appRoot, 'e2e-scenario.json');
const DEFAULT_SCENARIO = `${JSON.stringify({ scenario: 'launch' })}\n`;
if (!existsSync(scenarioFile)) {
  writeFileSync(scenarioFile, DEFAULT_SCENARIO);
  console.log('write-credentials: wrote the default e2e-scenario.json');
} else {
  const stale = (() => {
    try {
      const current = JSON.parse(readFileSync(scenarioFile, 'utf8'));
      return current === null || typeof current !== 'object' || 'endpoint' in current;
    } catch {
      return true;
    }
  })();
  if (stale) {
    writeFileSync(scenarioFile, DEFAULT_SCENARIO);
    console.log('write-credentials: reset e2e-scenario.json to the default (it carried an endpoint or was unreadable)');
  }
}

const iosToken = process.env.BUGSEE_TOKEN_IOS ?? '';
const androidToken = process.env.BUGSEE_TOKEN_ANDROID ?? '';
const endpoint = process.env.BUGSEE_ENDPOINT ?? '';

if (!iosToken && !androidToken) {
  console.error(
    'write-credentials: set BUGSEE_TOKEN_IOS and/or BUGSEE_TOKEN_ANDROID.',
  );
  process.exit(1);
}

writeFileSync(
  join(appRoot, 'credentials.json'),
  `${JSON.stringify({ ios: iosToken, android: androidToken, endpoint }, null, 2)}\n`,
);

// The Gradle plugin reads this at configure time. It has to exist even for a
// build that will not upload anything, or the plugin fails the build.
mkdirSync(join(appRoot, 'android'), { recursive: true });
const properties = [
  '# Generated by scripts/write-credentials.mjs. Never commit this file.',
  `app_token=${androidToken}`,
];
if (androidToken && !isPlaceholderToken(androidToken)) {
  properties.push('plugin.ndk.enabled=true');
}
if (endpoint) {
  properties.push(`plugin.endpoint=${endpoint}`);
}
properties.push('');
writeFileSync(join(appRoot, 'android', 'bugsee.properties'), properties.join('\n'));

console.log('write-credentials: wrote credentials.json and android/bugsee.properties');
