/**
 * Same rule as `isPlaceholderToken` in examples/bare/endpoint.ts. The CI
 * token `00000000-0000-4000-8000-000000000000` matches. Copied here so the
 * plugin does not import the example app.
 */
const PLACEHOLDER_TOKEN = /^0{12}[0-9a-f]0{3}[0-9a-f]0{15}$/i;

export function isPlaceholderToken(token: string): boolean {
  return PLACEHOLDER_TOKEN.test(token.replace(/-/g, ''));
}

export interface PropertiesInput {
  readonly appToken?: string;
  /** Defaults on. Opt out with `false`. */
  readonly nativeCrashReporting?: boolean;
  /** A base `pluginEndpoint` validated; written as `plugin.endpoint`. */
  readonly endpoint?: string;
}

/**
 * `<rootProject>/bugsee.properties`. The token is the unprefixed `app_token`
 * key, written only for a real token: the Gradle plugin uploads the R8
 * mapping and registers the APK with any `app_token` it finds, so a
 * placeholder would reach `plugin.endpoint`, or production. For the same
 * token, `plugin.ndk.enabled=true` follows while native crash reporting is on
 * (the default). `plugin.appToken` is not a key the Gradle plugin reads, and
 * this file never emits it. `plugin.endpoint` is the `endpoint` option, for
 * every Gradle upload; without it the plugin's default, production, stands.
 */
export function bugseePropertiesText(input: PropertiesInput = {}): string {
  const token = input.appToken ?? '';
  const lines: string[] = [];
  if (token.length > 0 && !isPlaceholderToken(token)) {
    lines.push(`app_token=${token}`);
    if (input.nativeCrashReporting !== false) {
      lines.push('plugin.ndk.enabled=true');
    }
  }
  if (input.endpoint) {
    lines.push(`plugin.endpoint=${input.endpoint}`);
  }
  if (lines.length === 0) {
    return '# Generated by @bugsee/react-native. No app token configured.\n';
  }
  return `${lines.join('\n')}\n`;
}
