import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { endpointFor } from '../../../src/options/endpoint';
import { rewriteBundlePhase } from '../bundle-phase';
import { dsymPostActionScript } from '../dsym-script';
import { ENDPOINT_HAS_VERSION, ENDPOINT_NOT_VALID, iosRuntimeEndpoint, pluginEndpoint } from '../endpoint';
import {
  RN_ENDPOINT_META_DATA,
  SDK_ENDPOINT_KEPT,
  SDK_ENDPOINT_MARKER,
  SDK_ENDPOINT_META_DATA,
  endpointMetaData,
} from '../manifest';
import { bugseePropertiesText } from '../properties';

// Synthetic hosts only; the dead loopback endpoint is the e2e's.
const DEAD = 'https://127.0.0.1:9';

describe('pluginEndpoint', () => {
  it('is unset for a missing, null, empty or blank value', () => {
    expect(pluginEndpoint(undefined)).toBeUndefined();
    expect(pluginEndpoint(null)).toBeUndefined();
    expect(pluginEndpoint('')).toBeUndefined();
    expect(pluginEndpoint(' \t\n')).toBeUndefined();
  });

  it.each([
    [DEAD, DEAD],
    [`${DEAD}/`, DEAD],
    [' https://bugsee.example.com ', 'https://bugsee.example.com'],
    ['https://bugsee.example.com///', 'https://bugsee.example.com'],
    ['https://bugsee.example.com:8443/api/', 'https://bugsee.example.com:8443/api'],
    ['https://BUGSEE.example.com/a_b~c.d-e%20', 'https://BUGSEE.example.com/a_b~c.d-e%20'],
    ['https://bugsee.example.com/v2x', 'https://bugsee.example.com/v2x'],
    ['https://bugsee.example.com/v2/api', 'https://bugsee.example.com/v2/api'],
  ])('accepts %j as %j', (value, expected) => {
    expect(pluginEndpoint(value)).toBe(expected);
  });

  it.each([
    'http://bugsee.example.com',
    'bugsee.example.com',
    'https://',
    'https:///path',
    'https://user:pass@bugsee.example.com',
    'https://bugsee.example.com?x=1',
    'https://bugsee.example.com/#frag',
    "https://bugsee.example.com/'$(id)'",
    'https://bugsee.example.com/a b',
    'https://bugsee.example.com:99999',
    'https://bugsee.example.com:',
    'https://[::1]:9',
    'ftp://bugsee.example.com',
    'https://bugsee.example.com\nx',
    'https://bugsee.example.com/"',
    'https://bugsee.example.com/<x>',
    'https://bugsee.example.com/\\',
  ])('refuses %j without echoing it', (value) => {
    let message = '';
    try {
      pluginEndpoint(value);
    } catch (error) {
      message = (error as Error).message;
    }
    expect(message).toBe(ENDPOINT_NOT_VALID);
  });

  it('refuses a value that is not a string', () => {
    for (const value of [9, true, {}, ['https://bugsee.example.com']]) {
      expect(() => pluginEndpoint(value)).toThrow(ENDPOINT_NOT_VALID);
    }
  });

  it.each(['https://bugsee.example.com/v2', 'https://bugsee.example.com/V2/', 'https://bugsee.example.com/api/v2'])(
    'refuses the API version in %j',
    (value) => {
      expect(() => pluginEndpoint(value)).toThrow(ENDPOINT_HAS_VERSION);
    },
  );

  it('names the shape it wants', () => {
    expect(ENDPOINT_NOT_VALID).toContain('https');
    expect(ENDPOINT_HAS_VERSION).toContain('/v2');
  });
});

describe('iosRuntimeEndpoint', () => {
  // The native module applies this value verbatim, as launch() would have
  // passed endpointFor('ios', …): the two must agree.
  it.each([DEAD, 'https://bugsee.example.com', 'https://bugsee.example.com:8443/api'])(
    'is what endpointFor gives the iOS SDK for %j',
    (base) => {
      expect(iosRuntimeEndpoint(base)).toBe(endpointFor('ios', base).endpoint);
      expect(iosRuntimeEndpoint(base)).toBe(`${base}/v2`);
    },
  );
});

describe('bugsee.properties with an endpoint', () => {
  const REAL = 'aaaaaaaa-bbbb-4ccc-8ddd-eeeeeeeeeeee';
  const PLACEHOLDER = '00000000-0000-4000-8000-000000000000';

  it('adds plugin.endpoint after the token lines', () => {
    expect(bugseePropertiesText({ appToken: REAL, endpoint: DEAD })).toBe(
      `app_token=${REAL}\nplugin.ndk.enabled=true\nplugin.endpoint=${DEAD}\n`,
    );
    expect(bugseePropertiesText({ appToken: REAL, endpoint: DEAD, nativeCrashReporting: false })).toBe(
      `app_token=${REAL}\nplugin.endpoint=${DEAD}\n`,
    );
  });

  it('writes no placeholder token, with or without an endpoint', () => {
    expect(bugseePropertiesText({ appToken: PLACEHOLDER })).toBe(
      '# Generated by @bugsee/react-native. No app token configured.\n',
    );
    expect(bugseePropertiesText({ appToken: '000000000000a000b000000000000000' })).not.toContain('app_token');
    expect(bugseePropertiesText({ appToken: PLACEHOLDER, endpoint: DEAD })).toBe(`plugin.endpoint=${DEAD}\n`);
    expect(bugseePropertiesText({ endpoint: DEAD })).toBe(`plugin.endpoint=${DEAD}\n`);
  });

  it('writes no endpoint key without one', () => {
    expect(bugseePropertiesText({ appToken: REAL })).not.toContain('plugin.endpoint');
    expect(bugseePropertiesText({ appToken: REAL, endpoint: '' })).not.toContain('plugin.endpoint');
  });
});

describe('the bundle phase with an endpoint', () => {
  const EXPO = [
    'if [[ -f "$PODS_ROOT/../.xcode.env" ]]; then',
    '  source "$PODS_ROOT/../.xcode.env"',
    'fi',
    '`"$NODE_BINARY" --print "require(\'path\').dirname(require.resolve(\'react-native/package.json\')) + \'/scripts/react-native-xcode.sh\'"`',
    '',
  ].join('\n');

  it('exports it in the settings block, after the token, and replaces it on the next run', () => {
    const first = rewriteBundlePhase(EXPO, { iosAppToken: 'tok', endpoint: DEAD });
    expect(first.split('\n').slice(0, 4)).toEqual([
      '# >>> bugsee settings, written by the @bugsee/react-native config plugin',
      "export BUGSEE_PLUGIN_APP_TOKEN='tok'",
      `export BUGSEE_ENDPOINT='${DEAD}'`,
      '# <<< bugsee settings',
    ]);
    const second = rewriteBundlePhase(first, { endpoint: 'https://bugsee.example.com' });
    expect(second.match(/export BUGSEE_ENDPOINT=/g)).toHaveLength(1);
    expect(second).toContain("export BUGSEE_ENDPOINT='https://bugsee.example.com'");
    expect(rewriteBundlePhase(second, {})).toBe(rewriteBundlePhase(EXPO, {}));
  });
});

describe('the Archive post-action with an endpoint', () => {
  it('bakes it as the second line, and not at all without one', () => {
    expect(dsymPostActionScript('tok', DEAD).split('\n').slice(0, 3)).toEqual([
      'CREDS="${PROJECT_DIR}/../credentials.json"',
      `export BUGSEE_ENDPOINT='${DEAD}'`,
      "TOKEN='tok'",
    ]);
    expect(dsymPostActionScript('tok', undefined)).toBe(dsymPostActionScript('tok'));
    expect(dsymPostActionScript('tok', '')).toBe(dsymPostActionScript('tok'));
  });

  // The script must hand the CLI the baked endpoint, ahead of the
  // environment's and the credentials file's.
  it('hands bugsee-cli the baked endpoint over the environment and credentials.json', () => {
    const dir = mkdtempSync(join(tmpdir(), 'bugsee-dsym-endpoint-'));
    try {
      const seen = join(dir, 'seen');
      const cliDir = join(dir, 'node_modules/@bugsee/cli');
      mkdirSync(join(cliDir, 'bin'), { recursive: true });
      mkdirSync(join(dir, 'node_modules/@bugsee/react-native'), { recursive: true });
      writeFileSync(join(dir, 'node_modules/@bugsee/react-native/package.json'), '{"name":"@bugsee/react-native"}');
      writeFileSync(join(cliDir, 'package.json'), JSON.stringify({ name: '@bugsee/cli', bin: { 'bugsee-cli': 'bin/cli.js' } }));
      writeFileSync(
        join(cliDir, 'bin/cli.js'),
        `require('fs').writeFileSync(${JSON.stringify(seen)}, process.env.BUGSEE_ENDPOINT);\n`,
      );
      mkdirSync(join(dir, 'ios'));
      writeFileSync(join(dir, 'credentials.json'), JSON.stringify({ ios: 'tok', endpoint: 'https://127.0.0.1:19' }));
      const result = spawnSync('/bin/sh', ['-c', dsymPostActionScript('tok', DEAD)], {
        encoding: 'utf8',
        env: { PATH: '/usr/bin:/bin', BUGSEE_ENDPOINT: 'https://localhost:9', PROJECT_DIR: join(dir, 'ios'), NODE_BINARY: process.execPath },
      });
      expect(result.status).toBe(0);
      expect(existsSync(seen) ? readFileSync(seen, 'utf8') : null).toBe(DEAD);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });
});

describe('endpointMetaData', () => {
  const none = (): undefined => undefined;
  const from = (items: Record<string, string>) => (name: string) => items[name];

  it('only removes its own key when the option is unset', () => {
    expect(endpointMetaData({ autoLaunchToken: null, existing: none })).toEqual({ remove: [RN_ENDPOINT_META_DATA], set: {} });
    expect(endpointMetaData({ endpoint: '', autoLaunchToken: 'tok', existing: none })).toEqual({
      remove: [RN_ENDPOINT_META_DATA],
      set: {},
    });
  });

  it('sets the runtime key, and the SDK key with its marker only for auto-launch', () => {
    expect(endpointMetaData({ endpoint: DEAD, autoLaunchToken: null, existing: none })).toEqual({
      remove: [RN_ENDPOINT_META_DATA],
      set: { [RN_ENDPOINT_META_DATA]: DEAD },
    });
    expect(endpointMetaData({ endpoint: DEAD, autoLaunchToken: 'tok', existing: none })).toEqual({
      remove: [RN_ENDPOINT_META_DATA],
      set: { [RN_ENDPOINT_META_DATA]: DEAD, [SDK_ENDPOINT_META_DATA]: DEAD, [SDK_ENDPOINT_MARKER]: DEAD },
    });
  });

  it('removes an SDK key it marked, whatever the new options', () => {
    const ours = from({ [SDK_ENDPOINT_META_DATA]: DEAD, [SDK_ENDPOINT_MARKER]: DEAD, [RN_ENDPOINT_META_DATA]: DEAD });
    expect(endpointMetaData({ autoLaunchToken: null, existing: ours })).toEqual({
      remove: [RN_ENDPOINT_META_DATA, SDK_ENDPOINT_MARKER, SDK_ENDPOINT_META_DATA],
      set: {},
    });
    expect(endpointMetaData({ endpoint: 'https://bugsee.example.com', autoLaunchToken: 'tok', existing: ours })).toEqual({
      remove: [RN_ENDPOINT_META_DATA, SDK_ENDPOINT_MARKER, SDK_ENDPOINT_META_DATA],
      set: {
        [RN_ENDPOINT_META_DATA]: 'https://bugsee.example.com',
        [SDK_ENDPOINT_META_DATA]: 'https://bugsee.example.com',
        [SDK_ENDPOINT_MARKER]: 'https://bugsee.example.com',
      },
    });
  });

  it('keeps an SDK key it did not write, or one changed since, and says so only when it would have written one', () => {
    const own = from({ [SDK_ENDPOINT_META_DATA]: 'https://own.example.com' });
    expect(endpointMetaData({ endpoint: DEAD, autoLaunchToken: 'tok', existing: own })).toEqual({
      remove: [RN_ENDPOINT_META_DATA],
      set: { [RN_ENDPOINT_META_DATA]: DEAD },
      warning: SDK_ENDPOINT_KEPT,
    });
    expect(endpointMetaData({ endpoint: DEAD, autoLaunchToken: null, existing: own })).toEqual({
      remove: [RN_ENDPOINT_META_DATA],
      set: { [RN_ENDPOINT_META_DATA]: DEAD },
    });
    const edited = from({ [SDK_ENDPOINT_META_DATA]: 'https://own.example.com', [SDK_ENDPOINT_MARKER]: DEAD });
    expect(endpointMetaData({ endpoint: DEAD, autoLaunchToken: 'tok', existing: edited })).toEqual({
      remove: [RN_ENDPOINT_META_DATA, SDK_ENDPOINT_MARKER],
      set: { [RN_ENDPOINT_META_DATA]: DEAD },
      warning: SDK_ENDPOINT_KEPT,
    });
    expect(endpointMetaData({ autoLaunchToken: null, existing: edited })).toEqual({
      remove: [RN_ENDPOINT_META_DATA, SDK_ENDPOINT_MARKER],
      set: {},
    });
  });

  it('names the key it leaves', () => {
    expect(SDK_ENDPOINT_KEPT).toContain(SDK_ENDPOINT_META_DATA);
  });
});
